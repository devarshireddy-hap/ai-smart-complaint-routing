"""
Test semantic similarity between complaint texts.
"""

from typing import List

from ai.embeddings.embedding_generator import generate_embedding


def cosine_similarity(
    vector_a: List[float],
    vector_b: List[float]
) -> float:
    """
    Calculate cosine similarity between two vectors.

    The vectors generated by our embedding model are normalized,
    so their dot product is equivalent to cosine similarity.
    """
    return sum(a * b for a, b in zip(vector_a, vector_b))


complaint_a = "Water pipe near Block B is leaking."
complaint_b = "There is a pipeline leakage beside Block B."
complaint_c = "The security gate was left open overnight."


embedding_a = generate_embedding(complaint_a)
embedding_b = generate_embedding(complaint_b)
embedding_c = generate_embedding(complaint_c)


similarity_ab = cosine_similarity(embedding_a, embedding_b)
similarity_ac = cosine_similarity(embedding_a, embedding_c)


print("Complaint A:")
print(complaint_a)

print("\nComplaint B:")
print(complaint_b)

print("\nComplaint C:")
print(complaint_c)

print("\nSimilarity A <-> B:")
print(round(similarity_ab, 4))

print("\nSimilarity A <-> C:")
print(round(similarity_ac, 4))